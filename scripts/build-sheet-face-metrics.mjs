#!/usr/bin/env node
/**
 * Generates packages/engine/src/sheet/face-metrics.ts: the advance widths of
 * every glyph the sheet can draw (WinAnsi, see winAnsiText) in each body face
 * that ships its own font files, read from apps/client/public/sheets/fonts.
 *
 *   node scripts/build-sheet-face-metrics.mjs build   # write the module
 *   node scripts/build-sheet-face-metrics.mjs check   # regenerate in memory and fail on drift
 *
 * The sheet model lays card prose out in the engine worker, which never loads
 * a font file; with these tables it measures a Spectral or Alegreya Sans card
 * the way the writer will draw it, instead of with Helvetica's widths. Widths
 * are advances in 1/1000 em, without kerning or ligatures: the writer paints a
 * plain show-text operator, which a viewer lays out on advances alone. Each
 * face's cap height places a box's first line (see BOX_TEXT_TOP_INSET).
 */

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import fontkit from "@pdf-lib/fontkit";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const FONTS = join(ROOT, "apps", "client", "public", "sheets", "fonts");
const OUTPUT = join(ROOT, "packages", "engine", "src", "sheet", "face-metrics.ts");
const CONTRACT = join(ROOT, "packages", "engine", "dist", "sheet", "template-contract.js");

const { SHEET_FONT_FACES } = await import(CONTRACT);

/** Every character winAnsiText can leave in a drawn string. */
const CHARACTERS = [
  ...Array.from({ length: 0x7f - 0x20 }, (_, index) => String.fromCodePoint(0x20 + index)),
  ...Array.from({ length: 0x100 - 0xa1 }, (_, index) => String.fromCodePoint(0xa1 + index)),
  ..."€‚ƒ„…†‡ˆ‰Š‹ŒŽ‘’“”•–—˜™š›œžŸ",
].join("");

const STYLES = ["regular", "bold", "italic", "boldItalic"];

function capHeight(file) {
  const font = fontkit.create(readFileSync(join(FONTS, file)));
  return Math.round(font.capHeight / font.unitsPerEm * 1000) / 1000;
}

function advances(file) {
  const font = fontkit.create(readFileSync(join(FONTS, file)));
  const scale = 1000 / font.unitsPerEm;
  return [...CHARACTERS].map((character) => {
    const glyph = font.glyphForCodePoint(character.codePointAt(0));
    return Math.round(glyph.advanceWidth * scale * 10) / 10;
  });
}

const faces = Object.entries(SHEET_FONT_FACES)
  .filter(([, face]) => face.roles.includes("body") && face.files !== undefined)
  .map(([name, face]) => [name, Object.fromEntries(STYLES.map((style) => [style, advances(face.files[style] ?? face.files.regular)]))]);

const capHeights = Object.fromEntries(Object.entries(SHEET_FONT_FACES)
  .filter(([, face]) => face.roles.includes("body") && face.files !== undefined)
  .map(([name, face]) => [name, capHeight(face.files.regular)]));

const body = faces.map(([name, styles]) => [
  `  ${name}: {`,
  ...STYLES.map((style) => `    ${style}: [${styles[style].join(", ")}],`),
  "  },",
].join("\n")).join("\n");

const source = `// Generated by scripts/build-sheet-face-metrics.mjs from apps/client/public/sheets/fonts; do not edit.

/** The characters each width table covers, in table order. */
export const FACE_METRIC_CHARACTERS = ${JSON.stringify(CHARACTERS)};

/** Cap height as a fraction of the type size, per body face with font files (regular style). */
export const FACE_CAP_HEIGHTS: Readonly<Record<string, number>> = ${JSON.stringify(capHeights)};

/** Advance widths in 1/1000 em, per body face with font files, per style. */
export const FACE_METRICS: Readonly<Record<string, Readonly<Record<"regular" | "bold" | "italic" | "boldItalic", readonly number[]>>>> = {
${body}
};
`;

const mode = process.argv[2] ?? "check";
if (mode === "build") {
  writeFileSync(OUTPUT, source);
  console.log(`wrote ${OUTPUT}`);
} else {
  let current = "";
  try { current = readFileSync(OUTPUT, "utf8"); } catch { /* missing counts as drift */ }
  if (current !== source) {
    console.error("face-metrics.ts is out of date: run node scripts/build-sheet-face-metrics.mjs build");
    process.exit(1);
  }
  console.log("face metrics match the font files");
}
